/**
 * Compiles src/contracts/*.sol and emits a TypeScript module per contract
 * holding its ABI (as a const assertion, so viem infers argument and return
 * types straight from it) and its creation bytecode.
 *
 * Run with: npm run compile
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/contracts");
const SOURCES = ["MemeToken.sol", "MemeFactory.sol"];

const input = {
  language: "Solidity",
  sources: Object.fromEntries(
    SOURCES.map((file) => [file, { content: readFileSync(join(dir, file), "utf8") }]),
  ),
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));

const problems = output.errors ?? [];
const errors = problems.filter((e) => e.severity === "error");
for (const problem of problems.filter((e) => e.severity !== "error")) {
  console.warn(problem.formattedMessage);
}
if (errors.length > 0) {
  console.error(errors.map((e) => e.formattedMessage).join("\n"));
  process.exit(1);
}

// EIP-170 caps deployed code at 24576 bytes on most chains; creation code runs
// larger, so warn on the artifact rather than fail.
const LIMIT = 24576;

for (const file of SOURCES) {
  const name = file.replace(/\.sol$/, "");
  const contract = output.contracts[file][name];
  const bytecode = contract.evm.bytecode.object;
  const constName = name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toUpperCase();

  writeFileSync(
    join(dir, `${name}.ts`),
    [
      `// Generated by scripts/compile-contracts.mjs from ${file} — do not edit.`,
      `// solc ${solc.version()}`,
      "",
      `export const ${constName}_ABI = ${JSON.stringify(contract.abi, null, 2)} as const;`,
      "",
      `export const ${constName}_BYTECODE = "0x${bytecode}" as const;`,
      "",
    ].join("\n"),
  );

  const size = bytecode.length / 2;
  const flag = size > LIMIT ? "  <-- over the 24576 byte code limit" : "";
  console.log(`${name}: ${size} bytes of creation code${flag}`);
}
