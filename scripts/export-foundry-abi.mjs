/**
 * Bridges the Foundry project in `contracts/` to the Next.js front end.
 *
 * `forge build` writes artifacts to contracts/out/<File>.sol/<Contract>.json.
 * This reads those and emits a TypeScript module per contract into
 * src/contracts/, holding the ABI as a const assertion — so viem infers
 * argument and return types straight from the Solidity — plus the creation
 * bytecode for contracts the browser deploys itself.
 *
 * Run with: npm run compile:foundry   (or `npm run compile:all`)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const foundryRoot = join(root, "contracts");
const outDir = join(foundryRoot, "out");
const target = join(root, "src/contracts");

/** Contracts the front end imports. Add an entry to export another. */
const EXPORTS = [
  { file: "LaunchpadToken.sol", contract: "LaunchpadToken" },
  { file: "MerkleAirdrop.sol", contract: "MerkleAirdrop" },
];

function fail(message) {
  console.error(message);
  process.exit(1);
}

// forge is installed to ~/.foundry/bin, which is not always on a non-login
// shell's PATH; fall back to the canonical location before giving up.
function forgeBinary() {
  const candidates = ["forge", join(process.env.HOME ?? "", ".foundry/bin/forge")];
  for (const candidate of candidates) {
    try {
      execFileSync(candidate, ["--version"], { stdio: "ignore" });
      return candidate;
    } catch {
      // Try the next one.
    }
  }
  return null;
}

if (!existsSync(outDir)) {
  const forge = forgeBinary();
  if (!forge) {
    fail(
      "No Foundry artifacts and forge is not on PATH.\n" +
        "Install it with:  curl -L https://foundry.paradigm.xyz | bash && foundryup\n" +
        'Then add it to your shell:  export PATH="$PATH:$HOME/.foundry/bin"',
    );
  }
  console.log("No artifacts yet — running forge build...");
  execFileSync(forge, ["build"], { cwd: foundryRoot, stdio: "inherit" });
}

for (const { file, contract } of EXPORTS) {
  const artifactPath = join(outDir, file, `${contract}.json`);
  if (!existsSync(artifactPath)) {
    fail(`Missing artifact ${artifactPath}. Run \`forge build\` in contracts/ first.`);
  }

  const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
  const constName = contract.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
  const bytecode = artifact.bytecode?.object ?? "0x";
  const compiler = artifact.metadata?.compiler?.version ?? "unknown";

  writeFileSync(
    join(target, `${contract}.ts`),
    [
      `// Generated by scripts/export-foundry-abi.mjs from contracts/src/${file}`,
      `// solc ${compiler} — do not edit; re-run \`npm run compile:foundry\` instead.`,
      "",
      `export const ${constName}_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;`,
      "",
      `export const ${constName}_BYTECODE = "${bytecode}" as const;`,
      "",
    ].join("\n"),
  );

  const size = Math.max(0, (bytecode.length - 2) / 2);
  console.log(`${contract}: ${artifact.abi.length} ABI entries, ${size} bytes of creation code`);
}

console.log(`\nWrote TypeScript modules to src/contracts/`);
